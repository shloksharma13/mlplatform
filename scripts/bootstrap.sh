#!/usr/bin/env bash
set -Eeuo pipefail

readonly REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly VERSION_FILE="${REPO_ROOT}/docs/VERSIONS.md"

required=(docker kind kubectl helm terraform python3 uv make git jq yq)
optional=(gh hey act gitleaks hadolint pre-commit ruff pytest)
missing=()
version_lines=()

first_line() {
  sed -n '1p'
}

tool_version() {
  local tool="$1"

  case "${tool}" in
    docker) docker --version 2>&1 | first_line ;;
    kind) kind version 2>&1 | first_line ;;
    kubectl) kubectl version --client=true 2>&1 | first_line ;;
    helm) helm version --short 2>&1 | first_line ;;
    terraform) terraform version 2>&1 | first_line ;;
    python3) python3 --version 2>&1 | first_line ;;
    uv) uv --version 2>&1 | first_line ;;
    make) make --version 2>&1 | first_line ;;
    git) git --version 2>&1 | first_line ;;
    jq) jq --version 2>&1 | first_line ;;
    yq) yq --version 2>&1 | first_line ;;
    gh) gh --version 2>&1 | first_line ;;
    hey) hey --version 2>&1 | first_line ;;
    act) act --version 2>&1 | first_line ;;
    gitleaks) gitleaks version 2>&1 | first_line ;;
    hadolint) hadolint --version 2>&1 | first_line ;;
    pre-commit) pre-commit --version 2>&1 | first_line ;;
    ruff) ruff --version 2>&1 | first_line ;;
    pytest) pytest --version 2>&1 | first_line ;;
    *) "${tool}" --version 2>&1 | first_line ;;
  esac
}

record_tool() {
  local requirement="$1"
  local tool="$2"

  if command -v "${tool}" >/dev/null 2>&1; then
    local version
    version="$(tool_version "${tool}")"
    printf 'ok      %-12s %s\n' "${tool}" "${version}"
    version_lines+=("| ${tool} | ${version//|/\\|} | ${requirement} |")
  else
    printf 'missing %-12s (%s)\n' "${tool}" "${requirement}"
    if [[ "${requirement}" == "required" ]]; then
      missing+=("${tool}")
    fi
  fi
}

printf 'MLPlatform prerequisite check\n'
printf 'Repository: %s\n\n' "${REPO_ROOT}"

for tool in "${required[@]}"; do
  record_tool required "${tool}"
done

if python311_path="$(uv python find 3.11 2>/dev/null)"; then
  python311_version="$(${python311_path} --version 2>&1 | first_line)"
  printf 'ok      %-12s %s\n' "python3.11" "${python311_version}"
  version_lines+=("| python3.11 | ${python311_version} | required runtime |")
else
  printf 'missing %-12s (%s)\n' "python3.11" "required runtime"
  missing+=("python3.11")
fi

for tool in "${optional[@]}"; do
  record_tool optional "${tool}"
done

{
  printf '# Versions\n\n'
  printf 'Generated by `make bootstrap` on `%s`.\n\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '| Tool | Observed version | Requirement |\n'
  printf '|---|---|---|\n'
  printf '%s\n' "${version_lines[@]}"
  printf '\nProject dependency versions are pinned in `uv.lock`; container, Helm, action, and provider pins are added in their owning phases.\n'
} >"${VERSION_FILE}"

if ((${#missing[@]} > 0)); then
  printf '\nMissing required tools: %s\n' "${missing[*]}" >&2
  printf 'Install them and rerun `make bootstrap`.\n' >&2
  exit 1
fi

printf '\nAll required prerequisites are available.\n'
